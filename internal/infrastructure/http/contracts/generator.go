type Direction = spec.Direction

const (
	Input  = spec.Input
	Output = spec.Output
)

type Contract = spec.Contract

func Request[T any](name string) Contract  { return spec.Request[T](name) }
func Response[T any](name string) Contract { return spec.Response[T](name) }

type shape struct {
	typ       reflect.Type
	direction Direction
}
type generator struct {
	names   map[shape]string
	queue   []Contract
	used    map[string]shape
	runtime bool
	// base is the layer this output builds on; its types are referenced
	// through the Platform import instead of being declared again.
	base *Layer
}

// Modules names the frontend modules of one generated layer.
type Modules struct {
	Declarations string // TypeScript wire types, e.g. "@/types/generated/http-contracts"
	Schemas      string // runtime Zod schemas, e.g. "@/lib/generated/http-contract-schemas"
}

// PlatformModules are the platform's generated frontend modules.
var PlatformModules = Modules{Declarations: "@/types/generated/http-contracts", Schemas: "@/lib/generated/http-contract-schemas"}

// Layer is a generated set of wire types that a configuration's output builds
// on: the configuration imports these names instead of declaring them again.
type Layer struct {
	modules Modules
	names   map[shape]string
	used    map[string]shape
	roots   map[string]Direction
	shapes  map[string]reflect.Type
}

// NewLayer traverses the roots the same way generation does and records the
// names they produce, published from the given modules.
func NewLayer(modules Modules, roots []Contract) (*Layer, error) {
	g, _, err := traverse(roots, false, nil)
	if err != nil {
		return nil, err
	}
	layer := &Layer{modules: modules, names: g.names, used: g.used, roots: map[string]Direction{}, shapes: map[string]reflect.Type{}}
	for _, root := range roots {
		layer.roots[root.Name] = root.Direction
		layer.shapes[root.Name] = root.Type
	}
	return layer, nil
}

// Generate rejects unregistered custom codecs instead of guessing their wire
// representation from their internal Go fields.
func Generate(roots []Contract) ([]byte, error) {
	return generate(roots, false, nil, Modules{})
}

// GenerateSchemas uses the same traversal, codec mappings and facade probes as
// declarations. It validates wire shapes; application rules remain in services.
func GenerateSchemas(roots []Contract) ([]byte, error) {
	return generate(roots, true, nil, Modules{})
}

// GenerateOn declares the roots a configuration adds on top of base. Types the
// base already declares are imported from its modules; own names publish
// from modules.
func GenerateOn(base *Layer, modules Modules, roots []Contract, runtime bool) ([]byte, error) {
	return generate(roots, runtime, base, modules)
}

func traverse(roots []Contract, runtime bool, base *Layer) (*generator, map[string]string, error) {
	g := &generator{names: map[shape]string{}, used: map[string]shape{}, runtime: runtime, base: base}
	for _, root := range roots {
		if err := g.register(root); err != nil {
			return nil, nil, err
		}
	}
	declarations := map[string]string{}
	for index := 0; index < len(g.queue); index++ {
		contract := g.queue[index]
		body, err := g.describe(contract.Type, contract.Direction, true)
		if err != nil {
			return nil, nil, fmt.Errorf("contract %s: %w", contract.Name, err)
		}
		if runtime {
			declarations[contract.Name] = "export const " + contract.Name + "Schema: z.ZodType<Wire." + contract.Name + "> = z.lazy(() => " + body + ")\n"
		} else {
			declarations[contract.Name] = "export type " + contract.Name + " = " + body + "\n"
		}
	}
	return g, declarations, nil
}

func generate(roots []Contract, runtime bool, base *Layer, modules Modules) ([]byte, error) {
	_, declarations, err := traverse(roots, runtime, base)
	if err != nil {
		return nil, err
	}
	keys := make([]string, 0, len(declarations))
	for key := range declarations {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	var output bytes.Buffer
	output.WriteString("// Code generated by go run ./cmd/http-contracts. DO NOT EDIT.\n")
	output.WriteString("// HTTP codecs only; JSONB and signed protocols are intentionally separate.\n")
	if base != nil {
		var body strings.Builder
		for _, key := range keys {
			body.WriteString(declarations[key])
		}
		output.WriteString(layerImports(body.String(), runtime, base, modules))
	} else if runtime {
		output.WriteString("import { z } from \"zod\"\nimport { jsonValueSchema } from \"@/lib/json-value\"\nimport { minorUnitsSchema } from \"@/lib/money\"\nimport type * as Wire from \"@/types/generated/http-contracts\"\n\n")
		output.WriteString("import { quantityInputSchema } from \"@/lib/quantity\"\n\n")
	} else {
		output.WriteString("import type { JsonValue } from \"@/lib/json-value\"\nimport type { MinorUnits } from \"@/lib/money\"\n\n")
	}
	for _, key := range keys {
		output.WriteString(declarations[key])
		output.WriteByte('\n')
	}
	return output.Bytes(), nil
}

// layerImports names only the modules a configuration's output uses, so the
// generated file has no unused imports.
func layerImports(body string, runtime bool, base *Layer, modules Modules) string {
	uses := func(name string) bool {
		return regexp.MustCompile(`\b` + regexp.QuoteMeta(name) + `\b`).MatchString(body)
	}
	var imports strings.Builder
	if runtime {
		imports.WriteString("import { z } from \"zod\"\n")
		if uses("jsonValueSchema") {
			imports.WriteString("import { jsonValueSchema } from \"@/lib/json-value\"\n")
		}
		if uses("minorUnitsSchema") {
			imports.WriteString("import { minorUnitsSchema } from \"@/lib/money\"\n")
		}
		if uses("quantityInputSchema") {
			imports.WriteString("import { quantityInputSchema } from \"@/lib/quantity\"\n")
		}
		imports.WriteString("import type * as Wire from \"" + modules.Declarations + "\"\n")
		if strings.Contains(body, "Platform.") {
			imports.WriteString("import * as Platform from \"" + base.modules.Schemas + "\"\n")
		}
	} else {
		if uses("JsonValue") {
			imports.WriteString("import type { JsonValue } from \"@/lib/json-value\"\n")
		}
		if uses("MinorUnits") {
			imports.WriteString("import type { MinorUnits } from \"@/lib/money\"\n")
		}
		if strings.Contains(body, "Platform.") {
			imports.WriteString("import type * as Platform from \"" + base.modules.Declarations + "\"\n")
		}
	}
	imports.WriteString("\n")
	return imports.String()
}

func (g *generator) representation(declaration, schema string) string {
	if g.runtime {
		return schema
	}
	return declaration
}

func (g *generator) register(c Contract) error {
	key := shape{c.Type, c.Direction}
	if g.base != nil {
		// A name the base layer declares is imported from it, never redeclared.
		if existing, ok := g.base.used[c.Name]; ok {
			if existing != key {
				return fmt.Errorf("contract name %s is already declared by the platform with another shape", c.Name)
			}
			return nil
		}
	}
	if existing, ok := g.used[c.Name]; ok {
		if existing != key {
			return fmt.Errorf("duplicate contract name %s", c.Name)
		}
		return nil
	}
	g.used[c.Name] = key
	if _, ok := g.names[key]; !ok {
		g.names[key] = c.Name
	}
	g.queue = append(g.queue, c)
	return nil
}

func (g *generator) describe(t reflect.Type, direction Direction, inline bool) (string, error) {
	if t.Kind() == reflect.Pointer {
		inner, err := g.describe(t.Elem(), direction, false)
		return g.representation(inner+" | null", inner+".nullable()"), err
	}
	if t == reflect.TypeFor[httpvalue.StringDictionary]() {
		return g.representation("Record<string, string>", "z.record(z.string(), z.string())"), nil
	}
	if t == reflect.TypeFor[httpvalue.BusinessReference]() {
		return g.representation("string", "z.string().min(1)"), nil
	}
	if scalar, ok := scalarMapping(t, direction); ok {
		validators := map[string]string{
			"MinorUnits": "minorUnitsSchema", "number | string": "z.union([z.number().finite(), z.string()])",
			"number": "z.number().finite()", "string": "z.string()", "JsonValue": "jsonValueSchema",
		}
		validator, exists := validators[scalar]
		if !exists {
			return "", fmt.Errorf("missing schema for HTTP scalar %s", scalar)
		}
		if t == reflect.TypeFor[types.Quantity]() && direction == Input {
			validator = "quantityInputSchema"
		}
		return g.representation(scalar, validator), nil
	}
	if hasCustomCodec(t) {
		return "", fmt.Errorf("custom codec %v requires an explicit HTTP mapping", t)
	}
	if !inline && t.Kind() == reflect.Struct && t.Name() == "" {
		// A type built at run time (declarative registrations) has no Go
		// name; where it is also a root contract, refer to it by that name.
		key := shape{t, direction}
		if g.base != nil {
			if name, ok := g.base.names[key]; ok {
				return g.representation("Platform."+name, "Platform."+name+"Schema"), nil
			}
		}
		if name, ok := g.names[key]; ok {
			return g.representation(name, name+"Schema"), nil
		}
	}
	if !inline && t.Kind() == reflect.Struct && t.Name() != "" {
		key := shape{t, direction}
		if g.base != nil {
			if name, ok := g.base.names[key]; ok {
				return g.representation("Platform."+name, "Platform."+name+"Schema"), nil
			}
		}
		if name, ok := g.names[key]; ok {
			return g.representation(name, name+"Schema"), nil
		}
		prefix := strings.ReplaceAll(path.Base(t.PkgPath()), "_", "")
		name := strings.ToUpper(prefix[:1]) + prefix[1:] + t.Name()
		if direction == Input {
			name += "Input"
		}
		if err := g.register(Contract{Name: name, Type: t, Direction: direction}); err != nil {
			return "", err
		}
		return g.representation(name, name+"Schema"), nil
	}
	switch t.Kind() {
	case reflect.String:
		return g.representation("string", "z.string()"), nil
	case reflect.Bool:
		return g.representation("boolean", "z.boolean()"), nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return g.representation("number", "z.number().int()"), nil
	case reflect.Float32, reflect.Float64:
		return g.representation("number", "z.number().finite()"), nil
	case reflect.Interface:
		if t.NumMethod() != 0 {
			return "", fmt.Errorf("non-JSON interface %v", t)
		}
		return g.representation("JsonValue", "jsonValueSchema"), nil
	case reflect.Slice, reflect.Array:
		if t.Elem().Kind() == reflect.Uint8 {
			return g.representation("string", "z.string()"), nil
		} // JSON base64
		element, err := g.describe(t.Elem(), direction, false)
		return g.representation("Array<"+element+">", "z.array("+element+")"), err
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			return "", fmt.Errorf("non-string JSON map key %v", t)
		}
		value, err := g.describe(t.Elem(), direction, false)
		return g.representation("Record<string, "+value+">", "z.record(z.string(), "+value+")"), err
	case reflect.Struct:
		return g.object(t, direction)
	default:
		return "", fmt.Errorf("unsupported HTTP type %v", t)
	}
}

func scalarMapping(t reflect.Type, direction Direction) (string, bool) {
	switch t {
	case reflect.TypeFor[httpvalue.MinorUnits](), reflect.TypeFor[types.MinorUnits]():
		return "MinorUnits", true
	case reflect.TypeFor[types.Quantity]():
		if direction == Input {
			return "number | string", true
		}
		return "number", true
	case reflect.TypeFor[decimal.Decimal]():
		if direction == Input {
			return "number | string", true
		}
		return "string", true
	case reflect.TypeFor[id.ID](), reflect.TypeFor[time.Time](), reflect.TypeFor[types.RawAmount](), reflect.TypeFor[types.RawDelta]():
		return "string", true
	case reflect.TypeFor[json.RawMessage]():
		return "JsonValue", true
	case reflect.TypeFor[json.Number]():
		return "number", true
	default:
		return "", false
	}
}

func hasCustomCodec(t reflect.Type) bool {
	for _, codec := range []reflect.Type{reflect.TypeFor[json.Marshaler](), reflect.TypeFor[json.MarshalerTo](), reflect.TypeFor[encoding.TextMarshaler](), reflect.TypeFor[json.Unmarshaler](), reflect.TypeFor[json.UnmarshalerFrom](), reflect.TypeFor[encoding.TextUnmarshaler]()} {
		if t.Implements(codec) || reflect.PointerTo(t).Implements(codec) {
			return true
		}
	}
	return false
}

func (g *generator) object(t reflect.Type, direction Direction) (string, error) {
	type projectionField struct {
		reflect.StructField
		embeddedOptional bool
	}
	var fields []projectionField
	var collect func(reflect.Type, bool) error
	collect = func(t reflect.Type, embeddedOptional bool) error {
		for field := range t.Fields() {
			if !field.IsExported() {
				continue
			}
			name, _, _ := strings.Cut(field.Tag.Get("json"), ",")
			if name == "-" {
				continue
			}
			for _, option := range strings.Split(field.Tag.Get("json"), ",")[1:] {
				if option != "" && option != "omitempty" && option != "omitzero" {
					return fmt.Errorf("JSON option %q on %s requires an explicit HTTP projection", option, field.Name)
				}
			}
			if field.Anonymous && name == "" {
				embedded := field.Type
				optional := embeddedOptional || embedded.Kind() == reflect.Pointer
				if embedded.Kind() == reflect.Pointer {
					embedded = embedded.Elem()
				}
				if embedded.Kind() != reflect.Struct || hasCustomCodec(embedded) {
					return fmt.Errorf("embedded nullable/custom field %s requires an explicit projection", field.Name)
				}
				if err := collect(embedded, optional); err != nil {
					return err
				}
				continue
			}
			fields = append(fields, projectionField{field, embeddedOptional})
		}
		return nil
	}
	if err := collect(t, false); err != nil {
		return "", err
	}
	if len(fields) == 0 {
		return g.representation("Record<string, never>", "z.record(z.string(), z.never())"), nil
	}
	var result strings.Builder
	objectSchema := "z.object({\n"
	if direction == Input {
		objectSchema = "z.strictObject({\n"
	}
	result.WriteString(g.representation("{\n", objectSchema))
	seen := map[string]bool{}
	for _, field := range fields {
		name, _, _ := strings.Cut(field.Tag.Get("json"), ",")
		if name == "" {
			name = field.Name
		}
		if seen[name] {
			return "", fmt.Errorf("ambiguous JSON field %q; add an explicit transport projection", name)
		}
		seen[name] = true
		optional, nullable, err := fieldPresence(field.StructField, direction)
		optional = optional || field.embeddedOptional
		if err != nil {
			return "", fmt.Errorf("field %s: %w", name, err)
		}
		target := field.Type
		if target.Kind() == reflect.Pointer {
			target = target.Elem()
		}
		wire, err := g.describe(target, direction, false)
		if err != nil {
			return "", fmt.Errorf("field %s: %w", name, err)
		}
		if nullable {
			wire += g.representation(" | null", ".nullable()")
		}
		mark := ""
		if optional {
			if g.runtime {
				wire += ".optional()"
			} else {
				mark = "?"
			}
		}
		result.WriteString("  " + strconv.Quote(name) + mark + ": " + wire + g.representation("\n", ",\n"))
	}
	result.WriteString(g.representation("}", "})"))
	return result.String(), nil
}

// Probe the actual facade instead of assuming encoding/json/v1 omitempty
// semantics. In v2, false and numeric zero are present under omitempty.
func fieldPresence(field reflect.StructField, direction Direction) (optional, nullable bool, err error) {
	tag := field.Tag.Get("json")
	name, _, _ := strings.Cut(tag, ",")
	if name == "" {
		name = field.Name
		tag = name + tag
	}
	probe := reflect.StructOf([]reflect.StructField{{Name: "Value", Type: field.Type, Tag: reflect.StructTag("json:" + strconv.Quote(tag))}})
	encoded, err := jsoncodec.Marshal(reflect.New(probe).Interface())
	if err != nil {
		return false, false, err
	}
	var object map[string]json.RawMessage
	if err := json.Unmarshal(encoded, &object); err != nil {
		return false, false, err
	}
	value, present := object[name]
	optional, nullable = !present, bytes.Equal(value, []byte("null"))
	if direction == Input {
		required := false
		for _, constraint := range strings.Split(field.Tag.Get("binding"), ",") {
			if constraint == "required" {
				required = true
			}
		}
		optional = !required
		nullable = field.Type.Kind() == reflect.Pointer && !required
	}
	return optional, nullable, nil
}
