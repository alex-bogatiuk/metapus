package contracts

func securityRoutes() []RouteContract {
	routes := []RouteContract{{Scope: "api", Method: "POST", Path: "/auth/login", Request: "LoginRequest", ResponseVariants: []string{"LoginResponse", "MFAChallengeResponse"}}}
	add := func(method, path, request, response string) {
		routes = append(routes, RouteContract{Scope: "api", Method: method, Path: path, Request: request, Response: response})
	}
	add("POST", "/auth/register", "RegisterRequest", "UserResponse")
	add("POST", "/auth/refresh", "RefreshTokenRequest", "TokenResponse")
	routes[len(routes)-1].OptionalRequest = true // browser refresh uses its httpOnly cookie
	add("POST", "/auth/logout", "", "")
	add("GET", "/auth/me", "", "UserResponse")
	add("GET", "/auth/me/permissions", "", "PermissionCodesResponse")
	add("POST", "/auth/ws-ticket", "", "WebSocketTicketResponse")
	add("POST", "/auth/mfa/verify", "MFAVerifyRequest", "LoginResponse")
	add("POST", "/auth/mfa/enroll/start", "MFAEnrollStartRequest", "MFAEnrollStartResponse")
	add("POST", "/auth/mfa/enroll/start-session", "", "MFAEnrollStartResponse")
	add("POST", "/auth/mfa/enroll/confirm", "MFAEnrollConfirmRequest", "MFAEnrollConfirmResponse")
	add("POST", "/auth/mfa/backup-code", "MFABackupCodeRequest", "LoginResponse")
	add("POST", "/auth/mfa/backup-codes/regenerate", "", "MFABackupCodesResponse")
	add("POST", "/auth/mfa/reset", "MFAResetRequest", "AuthMessageResponse")
	add("POST", "/auth/step-up", "StepUpRequest", "StepUpResponse")
	add("POST", "/auth/assign-role", "AssignRoleRequest", "AuthMessageResponse")
	add("POST", "/auth/revoke-role", "AssignRoleRequest", "AuthMessageResponse")
	add("GET", "/auth/users", "", "AdminUserListResponse")
	add("POST", "/auth/users", "CreateUserAdminRequest", "UserResponse")
	add("GET", "/auth/users/:userId", "", "UserResponse")
	add("PUT", "/auth/users/:userId", "UpdateUserRequest", "UserResponse")
	add("GET", "/auth/users/:userId/effective-access", "", "EffectiveAccessResponse")
	add("POST", "/auth/users/:userId/impersonate", "", "LoginResponse")
	add("GET", "/auth/roles", "", "RoleListResponse")
	add("POST", "/auth/roles", "CreateRoleRequest", "RoleResponse")
	add("GET", "/auth/roles/:roleId", "", "RoleResponse")
	add("PUT", "/auth/roles/:roleId", "UpdateRoleRequest", "RoleResponse")
	add("DELETE", "/auth/roles/:roleId", "", "DeleteRoleResponse")
	add("GET", "/auth/roles/:roleId/permissions", "", "PermissionListResponse")
	add("PUT", "/auth/roles/:roleId/permissions", "SetRolePermissionsRequest", "AuthMessageResponse")
	add("GET", "/auth/permissions", "", "PermissionListResponse")
	add("GET", "/security/profiles", "", "SecurityProfileListResponse")
	add("GET", "/security/profiles/:id", "", "SecurityProfileResponse")
	add("POST", "/security/profiles", "CreateSecurityProfileRequest", "SecurityProfileResponse")
	add("PUT", "/security/profiles/:id", "UpdateSecurityProfileRequest", "SecurityProfileResponse")
	add("DELETE", "/security/profiles/:id", "", "SuccessResponse")
	add("GET", "/security/profiles/:id/users", "", "ProfileUserListResponse")
	add("POST", "/security/profiles/:id/users", "AssignProfileRequest", "SuccessResponse")
	add("DELETE", "/security/profiles/:id/users/:userId", "", "SuccessResponse")
	add("GET", "/security/profiles/:id/audit", "", "SecurityAuditListResponse")
	add("GET", "/security/profiles/:id/rules", "", "PolicyRuleListResponse")
	add("POST", "/security/profiles/:id/rules", "CreatePolicyRuleRequest", "PolicyRuleResponse")
	add("PUT", "/security/profiles/:id/rules/:ruleId", "UpdatePolicyRuleRequest", "PolicyRuleResponse")
	add("DELETE", "/security/profiles/:id/rules/:ruleId", "", "SuccessResponse")
	add("POST", "/security/rules/validate", "ValidateExpressionRequest", "ValidateExpressionResponse")
	add("POST", "/security/rules/test", "TestExpressionRequest", "TestExpressionResponse")
	add("GET", "/search", "", "SearchResponse")
	add("GET", "/search/preview", "", "PreviewResponse")
	return routes
}
