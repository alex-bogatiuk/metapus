// withCrypto applies the crypto configuration's migrations, which the
// migration database of the integration suite holds.
func withCrypto(t testing.TB) Option {
	t.Helper()
	source, err := dbassets.ConfigurationMigrations("crypto")
	require.NoError(t, err)
	require.NotNil(t, source)
	return WithConfiguration("crypto", source)
}

// scratchDatabase creates an empty database in the test cluster and returns
// its DSN.
func scratchDatabase(t *testing.T) string {
	t.Helper()
	admin := os.Getenv("TENANT_POSTGRES_TEST_URL")
	require.NotEmpty(t, admin, "TENANT_POSTGRES_TEST_URL must identify the disposable test cluster")
	ctx := context.Background()
	conn, err := pgx.Connect(ctx, admin)
	require.NoError(t, err)
	t.Cleanup(func() { _ = conn.Close(context.Background()) })
	name := "metapus_history_" + id.Compact(id.New())
	_, err = conn.Exec(ctx, "CREATE DATABASE "+pgx.Identifier{name}.Sanitize())
	require.NoError(t, err)
	t.Cleanup(func() {
		_, _ = conn.Exec(context.Background(), "DROP DATABASE IF EXISTS "+pgx.Identifier{name}.Sanitize()+" WITH (FORCE)")
	})
	target, err := url.Parse(admin)
	require.NoError(t, err)
	target.Path = "/" + name
	return target.String()
}

func appliedVersions(t *testing.T, db *sql.DB, table string) []int64 {
	t.Helper()
	rows, err := db.Query(`SELECT version_id FROM ` + table + ` WHERE is_applied ORDER BY id`)
	require.NoError(t, err)
	defer func() { _ = rows.Close() }()
	var versions []int64
	for rows.Next() {
		var v int64
		require.NoError(t, rows.Scan(&v))
		versions = append(versions, v)
	}
	require.NoError(t, rows.Err())
	return versions
}

// A database migrated while every tenant migration shared goose_db_version
// gets its history split once: the platform's, the configuration's and the
// extensions' versions move to their tables and nothing is applied twice.
func TestRunMovesTheSharedHistoryToItsTables(t *testing.T) {
	dsn := scratchDatabase(t)
	result, err := Run(dsn, withCrypto(t))
	require.NoError(t, err, result.Output)
	db, err := sql.Open("pgx", dsn)
	require.NoError(t, err)
	t.Cleanup(func() { _ = db.Close() })

	// Rebuild the history the way the shared goose_db_version kept it.
	platform := appliedVersions(t, db, PlatformVersionTable)
	crypto := appliedVersions(t, db, ConfigurationVersionTable("crypto"))
	_, err = db.Exec(`CREATE TABLE goose_db_version (
		id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
		version_id bigint NOT NULL, is_applied boolean NOT NULL,
		tstamp timestamp NOT NULL DEFAULT now())`)
	require.NoError(t, err)
	for _, v := range append(append(platform, crypto[1:]...), 10001) {
		_, err = db.Exec(`INSERT INTO goose_db_version (version_id, is_applied) VALUES ($1, true)`, v)
		require.NoError(t, err)
	}
	_, err = db.Exec(`DROP TABLE ` + PlatformVersionTable + `, ` + ConfigurationVersionTable("crypto"))
	require.NoError(t, err)

	// Without its configuration the shared history cannot be placed.
	_, err = Run(dsn)
	require.ErrorIs(t, err, tenant.ErrConfigurationMismatch)
	_, err = Run(dsn, WithConfiguration("other", nil))
	require.ErrorIs(t, err, tenant.ErrConfigurationMismatch)

	result, err = Run(dsn, withCrypto(t))
	require.NoError(t, err, result.Output)
	require.Contains(t, result.Output, fmt.Sprintf("%d platform, %d crypto, 1 extension versions", len(platform), len(crypto)-1))
	require.NotContains(t, result.Output, "applied (")
	require.Equal(t, version.ExpectedSchemaVersion, result.Schema.Version)
	require.Equal(t, platform, appliedVersions(t, db, PlatformVersionTable))
	require.Equal(t, crypto, appliedVersions(t, db, ConfigurationVersionTable("crypto")))
	require.Equal(t, []int64{0, 10001}, appliedVersions(t, db, ExtensionsVersionTable))
	var shared bool
	require.NoError(t, db.QueryRow(`SELECT to_regclass('goose_db_version') IS NOT NULL`).Scan(&shared))
	require.False(t, shared)
}

// A tenant database holds one configuration's migrations for life.
func TestRunRefusesADatabaseOfAnotherConfiguration(t *testing.T) {
	dsn := scratchDatabase(t)
	result, err := Run(dsn, withCrypto(t))
	require.NoError(t, err, result.Output)

	_, err = Run(dsn, WithConfiguration("none", nil))
	require.ErrorIs(t, err, tenant.ErrConfigurationMismatch)
	require.ErrorContains(t, err, `configuration "crypto", not "none"`)

	// The platform's migrations alone apply to a database of any
	// configuration.
	result, err = Run(dsn)
	require.NoError(t, err, result.Output)
	require.Equal(t, tenant.Schema{Version: version.ExpectedSchemaVersion}, result.Schema)

	fresh := scratchDatabase(t)
	result, err = Run(fresh, WithConfiguration("none", nil))
	require.NoError(t, err, result.Output)
	require.Equal(t, tenant.Schema{Configuration: "none", Version: version.ExpectedSchemaVersion}, result.Schema)
	var cryptoTable bool
	db, err := sql.Open("pgx", fresh)
	require.NoError(t, err)
	t.Cleanup(func() { _ = db.Close() })
	require.NoError(t, db.QueryRow(`SELECT to_regclass('doc_crypto_invoices') IS NOT NULL`).Scan(&cryptoTable))
	require.False(t, cryptoTable)
	_, err = Run(fresh, withCrypto(t))
	require.ErrorIs(t, err, tenant.ErrConfigurationMismatch)
}
