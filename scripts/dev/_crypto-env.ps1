$script:CryptoRepoRoot = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path
$script:CryptoEnvPath = Join-Path $script:CryptoRepoRoot ".env.crypto.local"

function Read-CryptoEnvFile {
    param(
        [string]$Path = $script:CryptoEnvPath
    )

    $values = @{}
    if (-not (Test-Path $Path)) {
        return $values
    }

    foreach ($line in Get-Content -Path $Path) {
        $trimmed = $line.Trim()
        if ($trimmed -eq "" -or $trimmed.StartsWith("#")) {
            continue
        }

        $index = $trimmed.IndexOf("=")
        if ($index -lt 1) {
            continue
        }

        $name = $trimmed.Substring(0, $index).Trim()
        if ($name -notmatch "^[A-Za-z_][A-Za-z0-9_]*$") {
            continue
        }

        $value = $trimmed.Substring($index + 1)
        $values[$name] = $value
    }

    return $values
}

function Import-CryptoEnv {
    param(
        [string]$Path = $script:CryptoEnvPath
    )

    $values = Read-CryptoEnvFile -Path $Path
    foreach ($key in $values.Keys) {
        [Environment]::SetEnvironmentVariable($key, [string]$values[$key], "Process")
    }
    return $values
}

function Write-CryptoEnvFile {
    param(
        [hashtable]$Values,
        [string[]]$RemoveKeys = @(),
        [string]$Path = $script:CryptoEnvPath
    )

    $merged = Read-CryptoEnvFile -Path $Path
    foreach ($key in $RemoveKeys) {
        $merged.Remove($key) | Out-Null
        [Environment]::SetEnvironmentVariable($key, $null, "Process")
    }
    foreach ($key in $Values.Keys) {
        if ($null -eq $Values[$key]) {
            continue
        }
        $merged[$key] = [string]$Values[$key]
        [Environment]::SetEnvironmentVariable($key, [string]$Values[$key], "Process")
    }

    $orderedKeys = @(
