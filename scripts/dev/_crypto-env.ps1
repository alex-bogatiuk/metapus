        "CRYPTO_RESOURCE_LEASE_TARGET_ENERGY",
        "CRYPTO_RESOURCE_SAFETY_MARGIN_PCT",
        "CRYPTO_RESOURCE_RESERVATION_CUTOFF_SECONDS",
        "MERCHANT_ID",
        "TOKEN_ID",
        "NETWORK_ID",
        "MERCHANT_API_KEY"
    )

    $lines = @(
        "# Generated by scripts/dev/crypto-setup.ps1.",
        "# Local dev/test secrets only. Do not commit."
    )

    $written = @{}
    foreach ($key in $orderedKeys) {
        if ($merged.ContainsKey($key)) {
            $lines += "$key=$($merged[$key])"
            $written[$key] = $true
        }
    }
    foreach ($key in ($merged.Keys | Sort-Object)) {
        if (-not $written.ContainsKey($key)) {
            $lines += "$key=$($merged[$key])"
        }
    }

    Set-Content -Path $Path -Value $lines -Encoding UTF8
}

function Get-CryptoRequiredEnv {
    param([string]$Name)
    $value = [Environment]::GetEnvironmentVariable($Name, "Process")
    if ([string]::IsNullOrWhiteSpace($value)) {
        throw "Required environment variable '$Name' is missing. Run scripts/dev/crypto-setup.ps1 first."
    }
    return $value
}

function Invoke-CryptoNative {
    param(
        [string]$Description,
        [scriptblock]$Command
    )

    Write-Host "==> $Description"
    & $Command
    if ($LASTEXITCODE -ne 0) {
        throw "$Description failed with exit code $LASTEXITCODE"
    }
}

function Assert-CryptoDockerReady {
    & docker version *> $null
    if ($LASTEXITCODE -ne 0) {
        throw "Docker Desktop is not running or Docker API is unavailable. Start Docker Desktop and retry."
    }
}

function Invoke-CryptoPsql {
    param(
        [string]$Database,
        [string]$Sql
    )

    Assert-CryptoDockerReady
    $output = & docker exec metapus-db psql -U metapus -d $Database -t -A -c $Sql
    if ($LASTEXITCODE -ne 0) {
        throw "psql failed for database '$Database'"
    }
    return (($output | Where-Object { $_ -ne "" }) -join "`n").Trim()
}

function ConvertTo-CryptoSqlLiteral {
    param([string]$Value)
    return $Value.Replace("'", "''")
}
